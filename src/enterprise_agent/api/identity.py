"""Local identity, auth_sessions, feedback and immutable request audit for one deployment."""

import getpass
import hashlib
import hmac
import os
import secrets
import sys
from contextlib import contextmanager
from datetime import datetime, timedelta, timezone

from fastapi import Depends, Header, HTTPException

from threading import Lock
from psycopg.rows import dict_row
from ..core.config import database_url, setting
from ..persistence.postgres import Postgres

AUTH_DSN = None
AUTH_SCHEMA = "identity"
SESSION_HOURS = int(os.getenv("SESSION_HOURS", "12"))
_clients = {}
_client_lock = Lock()


def _now():
    return datetime.now(timezone.utc)


def auth_persistence():
    key = (AUTH_DSN or database_url(), AUTH_SCHEMA)
    with _client_lock:
        if key not in _clients:
            client = Postgres(key[0], key[1], max_size=8)
            try:
                client.setup(
                    1,
                    [
                        "CREATE TABLE IF NOT EXISTS users(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,username TEXT NOT NULL UNIQUE,password_hash TEXT NOT NULL,role TEXT NOT NULL CHECK(role IN ('admin','analyst','viewer')),active BOOLEAN NOT NULL DEFAULT TRUE,created_at TIMESTAMPTZ NOT NULL)",
                        "CREATE TABLE IF NOT EXISTS auth_sessions(token_hash TEXT PRIMARY KEY,user_id BIGINT NOT NULL REFERENCES users(id),expires_at TIMESTAMPTZ NOT NULL,created_at TIMESTAMPTZ NOT NULL)",
                        "CREATE TABLE IF NOT EXISTS login_failures(username TEXT PRIMARY KEY,attempts INTEGER NOT NULL,first_at TIMESTAMPTZ NOT NULL)",
                        "CREATE TABLE IF NOT EXISTS audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,at TIMESTAMPTZ NOT NULL,user_id BIGINT REFERENCES users(id),action TEXT NOT NULL,status TEXT NOT NULL,question_hash TEXT,sql_hash TEXT,snapshot_id TEXT,metric_version TEXT,duration_ms INTEGER,detail TEXT)",
                        "CREATE TABLE IF NOT EXISTS feedback(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,at TIMESTAMPTZ NOT NULL,user_id BIGINT NOT NULL REFERENCES users(id),audit_id BIGINT REFERENCES audit(id),rating INTEGER NOT NULL CHECK(rating BETWEEN 1 AND 5),comment TEXT NOT NULL)",
                        "CREATE INDEX IF NOT EXISTS ix_audit_at ON audit(at DESC)",
                        "CREATE INDEX IF NOT EXISTS ix_audit_user ON audit(user_id,at DESC)",
                        "CREATE INDEX IF NOT EXISTS ix_auth_expiry ON auth_sessions(expires_at)",
                    ],
                )
            except BaseException:
                client.close()
                raise
            _clients[key] = client
        return _clients[key]


def close():
    with _client_lock:
        for client in _clients.values():
            client.close()
        _clients.clear()


@contextmanager
def app_db():
    with auth_persistence().pool.connection() as db:
        db.row_factory = dict_row
        yield db


def setup():
    auth_persistence()


def _password_hash(password):
    if len(password) < 12:
        raise ValueError("密码至少 12 位")
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode(), salt, 240_000)
    return f"pbkdf2_sha256$240000${salt.hex()}${digest.hex()}"


def _verify(password, encoded):
    try:
        _, rounds, salt, digest = encoded.split("$")
        actual = hashlib.pbkdf2_hmac(
            "sha256", password.encode(), bytes.fromhex(salt), int(rounds)
        )
        return hmac.compare_digest(actual, bytes.fromhex(digest))
    except (ValueError, TypeError):
        return False


def create_user(username, password, role="analyst"):
    if role not in ("admin", "analyst", "viewer") or not username or len(username) > 64:
        raise ValueError("账号或角色无效")
    setup()
    with app_db() as db:
        cur = db.execute(
            "INSERT INTO users(username,password_hash,role,created_at) VALUES(%s,%s,%s,%s) RETURNING id",
            (username, _password_hash(password), role, _now().isoformat()),
        )
        return cur.fetchone()["id"]


def bootstrap_admin():
    setup()
    with app_db() as db:
        if db.execute("SELECT 1 FROM users LIMIT 1").fetchone():
            return False
    password = setting("INITIAL_ADMIN_PASSWORD")
    if not password and sys.stdin.isatty():
        password = getpass.getpass("Initial admin password (12+ chars): ")
    if not password:
        raise SystemExit("Set INITIAL_ADMIN_PASSWORD or run interactively")
    create_user("admin", password, "admin")
    return True


def login(username, password):
    setup()
    with app_db() as db:
        db.execute(
            "SELECT pg_advisory_xact_lock(hashtextextended(%s,0))",
            (f"enterprise-login:{AUTH_SCHEMA}:{username}",),
        )
        failure = db.execute(
            "SELECT attempts,first_at FROM login_failures WHERE username=%s",
            (username,),
        ).fetchone()
        window = (_now() - timedelta(minutes=15)).isoformat()
        if (
            failure
            and failure["attempts"] >= 5
            and failure["first_at"] > datetime.fromisoformat(window)
        ):
            raise HTTPException(429, "登录尝试过多，请 15 分钟后重试")
        row = db.execute(
            "SELECT * FROM users WHERE username=%s AND active=TRUE", (username,)
        ).fetchone()
        if not row or not _verify(password, row["password_hash"]):
            if not failure or failure["first_at"] <= datetime.fromisoformat(window):
                db.execute(
                    "INSERT INTO login_failures(username,attempts,first_at) VALUES(%s,1,%s) ON CONFLICT(username) DO UPDATE SET attempts=1,first_at=excluded.first_at",
                    (username, _now().isoformat()),
                )
            else:
                db.execute(
                    "UPDATE login_failures SET attempts=attempts+1 WHERE username=%s",
                    (username,),
                )
            db.commit()
            raise HTTPException(401, "账号或密码错误")
        db.execute("DELETE FROM login_failures WHERE username=%s", (username,))
        token = secrets.token_urlsafe(40)
        db.execute(
            "DELETE FROM auth_sessions WHERE expires_at < %s", (_now().isoformat(),)
        )
        db.execute(
            "INSERT INTO auth_sessions VALUES(%s,%s,%s,%s)",
            (
                hashlib.sha256(token.encode()).hexdigest(),
                row["id"],
                (_now() + timedelta(hours=SESSION_HOURS)).isoformat(),
                _now().isoformat(),
            ),
        )
        return {
            "access_token": token,
            "token_type": "bearer",
            "expires_in": SESSION_HOURS * 3600,
            "user": {"id": row["id"], "username": row["username"], "role": row["role"]},
        }


def current_user(authorization: str | None = Header(default=None)):
    if not authorization or not authorization.startswith("Bearer "):
        raise HTTPException(401, "请先登录")
    token = authorization[7:]
    if len(token) > 256:
        raise HTTPException(401, "会话无效")
    with app_db() as db:
        row = db.execute(
            "SELECT u.id,u.username,u.role,u.active,s.expires_at FROM auth_sessions s JOIN users u ON u.id=s.user_id WHERE s.token_hash=%s",
            (hashlib.sha256(token.encode()).hexdigest(),),
        ).fetchone()
    if not row or not row["active"] or row["expires_at"] < _now():
        raise HTTPException(401, "会话已过期")
    return dict(row)


def require(*roles):
    def check(user=Depends(current_user)):
        if user["role"] not in roles:
            raise HTTPException(403, "当前角色无权执行此操作")
        return user

    return check


def logout(authorization):
    if authorization and authorization.startswith("Bearer "):
        token_hash = hashlib.sha256(authorization[7:].encode()).hexdigest()
        with app_db() as db:
            db.execute("DELETE FROM auth_sessions WHERE token_hash=%s", (token_hash,))


def change_password(user_id, old_password, new_password):
    with app_db() as db:
        row = db.execute(
            "SELECT password_hash FROM users WHERE id=%s AND active=TRUE", (user_id,)
        ).fetchone()
        if not row or not _verify(old_password, row["password_hash"]):
            raise HTTPException(400, "当前密码错误")
        db.execute(
            "UPDATE users SET password_hash=%s WHERE id=%s",
            (_password_hash(new_password), user_id),
        )
        db.execute("DELETE FROM auth_sessions WHERE user_id=%s", (user_id,))


def audit(
    user_id,
    action,
    status,
    question=None,
    sql_hash=None,
    snapshot_id=None,
    metric_version=None,
    duration_ms=None,
    detail=None,
):
    with app_db() as db:
        cur = db.execute(
            "INSERT INTO audit(at,user_id,action,status,question_hash,sql_hash,snapshot_id,metric_version,duration_ms,detail) VALUES(%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) RETURNING id",
            (
                _now().isoformat(),
                user_id,
                action,
                status,
                hashlib.sha256(question.encode()).hexdigest() if question else None,
                sql_hash,
                snapshot_id,
                metric_version,
                duration_ms,
                detail[:500] if detail else None,
            ),
        )
        return cur.fetchone()["id"]


def list_audit(user, limit=50):
    with app_db() as db:
        if user["role"] == "admin":
            rows = db.execute(
                "SELECT a.id,a.at,u.username,a.action,a.status,a.sql_hash,a.snapshot_id,a.metric_version,a.duration_ms,a.detail FROM audit a LEFT JOIN users u ON u.id=a.user_id ORDER BY a.id DESC LIMIT %s",
                (limit,),
            ).fetchall()
        else:
            rows = db.execute(
                "SELECT id,at,action,status,sql_hash,snapshot_id,metric_version,duration_ms,detail FROM audit WHERE user_id=%s ORDER BY id DESC LIMIT %s",
                (user["id"], limit),
            ).fetchall()
    return [dict(r) for r in rows]


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "bootstrap":
        print("Admin created" if bootstrap_admin() else "Users already exist")
